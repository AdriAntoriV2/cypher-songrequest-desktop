
$ErrorActionPreference = "Stop"

# CypherSR Desktop frontend build.
# Compiles the Rust/Slint GUI only.
# Project root is detected relative to this script.

$FrontendRoot = Split-Path -Parent $PSScriptRoot
$CargoManifest = Join-Path $FrontendRoot "Cargo.toml"
$ReleaseDir = Join-Path $FrontendRoot "target\release"

function Require-Path {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [string]$Description = "Required path"
    )

    if (-not (Test-Path -LiteralPath $Path)) {
        throw "$Description not found: $Path"
    }
}

Require-Path -Path $CargoManifest -Description "Desktop Cargo.toml"

if (-not (Get-Command "cargo" -ErrorAction SilentlyContinue)) {
    throw "Cargo was not found. Install Rust and reopen the terminal."
}

Write-Host ""
Write-Host "============================================"
Write-Host "Building CypherSR Desktop"
Write-Host "============================================"
Write-Host "Project: $FrontendRoot"
Write-Host ""

Push-Location $FrontendRoot

try {
    cargo build --release --manifest-path $CargoManifest

    if ($LASTEXITCODE -ne 0) {
        throw "Desktop build failed with exit code $LASTEXITCODE."
    }
}
finally {
    Pop-Location
}

Require-Path -Path $ReleaseDir -Description "Cargo release output directory"

# Discover the executable generated by the build.
$executables = @(
    Get-ChildItem -LiteralPath $ReleaseDir -Filter "*.exe" -File |
        Where-Object { $_.Name -notlike "*.pdb.exe" }
)

if ($executables.Count -eq 0) {
    throw "No executable was found in $ReleaseDir."
}

if ($executables.Count -gt 1) {
    $expectedExe = $executables |
        Where-Object { $_.BaseName -eq "CypherSR-Desktop" }

    if ($expectedExe) {
        $builtExe = $expectedExe
    }
    else {
        $names = ($executables | ForEach-Object { $_.Name }) -join ", "
        throw "Multiple executables found in $ReleaseDir; cannot determine which is the Desktop GUI: $names"
    }
}
else {
    $builtExe = $executables[0]
}

Write-Host ""
Write-Host "============================================"
Write-Host "Desktop build completed successfully"
Write-Host "============================================"
Write-Host "Executable: $($builtExe.FullName)"
Write-Host ""
